let currentLang = 'en';

function toggleLanguage() {
  currentLang = (currentLang === 'en') ? 'ar' : 'en';
  applyLanguage(currentLang);
}

function applyLanguage(lang) {
  currentLang = lang;
  const t = translations[lang];
  if (!t) return;

  // Set HTML lang and dir attribute for instant RTL / LTR switching
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

  // Add an RTL class to body for custom styling if needed
  if (lang === 'ar') {
    document.body.classList.add('rtl-mode');
  } else {
    document.body.classList.remove('rtl-mode');
  }

  // Update text content for all elements with data-i18n attribute FIRST
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // Update placeholders
  const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
  placeholders.forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) {
      el.setAttribute('placeholder', t[key]);
    }
  });

  // Re-initialize Owl Carousel for Testimonials in new RTL / LTR direction AFTER translating text
  if (typeof window.initTestimonialCarousel === 'function') {
    window.initTestimonialCarousel();
  }

  // Update countdown timer labels immediately on language toggle
  if (typeof window.makeTimer === 'function') {
    window.makeTimer();
  }

  // Remove FOUC fix style if present and show body smoothly
  const foucStyle = document.getElementById('rtl-fouc-fix');
  if (foucStyle) {
    foucStyle.remove();
  }
  if (document.body) {
    document.body.style.opacity = '1';
  }

  // Update budget slider input display if initialized
  const curr = lang === 'ar' ? ' ج.م' : ' EGP';
  if (typeof $ !== 'undefined' && $('#slider-range').length && $('#slider-range').hasClass('ui-slider')) {
    $('#amount').val($('#slider-range').slider('values', 0).toLocaleString() + curr + ' - ' + $('#slider-range').slider('values', 1).toLocaleString() + curr);
    $('#amount-hajj').val($('#slider-range-hajj').slider('values', 0).toLocaleString() + curr + ' - ' + $('#slider-range-hajj').slider('values', 1).toLocaleString() + curr);
    $('#amount-ziyarat').val($('#slider-range-ziyarat').slider('values', 0).toLocaleString() + curr + ' - ' + $('#slider-range-ziyarat').slider('values', 1).toLocaleString() + curr);
  }

  // Re-trigger hero staggered animation when language changes
  const heroBox = document.querySelector('.hero-stagger-box');
  if (heroBox) {
    heroBox.classList.remove('hero-stagger-box');
    void heroBox.offsetWidth;
    heroBox.classList.add('hero-stagger-box');
  }

  // Save preference
  try {
    localStorage.setItem('nuralharamain_lang', lang);
  } catch(e) {}
}

// Auto load language immediately (synchronous execution to ensure DOM translates before custom.js initializes animations)
(function() {
  let savedLang = 'en';
  try {
    savedLang = localStorage.getItem('nuralharamain_lang') || 'en';
  } catch(e) {}
  if (savedLang === 'ar') {
    applyLanguage('ar');
  }
})();

document.addEventListener('DOMContentLoaded', () => {
  let savedLang = 'en';
  try {
    savedLang = localStorage.getItem('nuralharamain_lang') || 'en';
  } catch(e) {}
  if (savedLang === 'ar' && currentLang !== 'ar') {
    applyLanguage('ar');
  } else if (savedLang === 'ar') {
    // Just remove FOUC style if DOMContentLoaded fired after immediate run
    const foucStyle = document.getElementById('rtl-fouc-fix');
    if (foucStyle) foucStyle.remove();
    if (document.body) document.body.style.opacity = '1';
  }
});
